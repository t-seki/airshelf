    [Fact]
    public void Find_DoesNotGroupAcrossStations()
    {
        var groups = SiblingFolders.Find(
        [
            new("TBSラジオ", "番組(1)"),
            new("文化放送", "番組(2)"),
        ]);

        Assert.Empty(groups);
    }

    [Fact]
    public void Find_CountsTheSameFolderOnce()
    {
        // 台帳には同じフォルダの回が何件もある。1 フォルダだけでは兄弟にならない。
        var groups = SiblingFolders.Find(
        [
            new("TBSラジオ", "番組(1)"),
            new("TBSラジオ", "番組(1)"),
        ]);

        Assert.Empty(groups);
    }
